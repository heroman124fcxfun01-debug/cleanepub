#!/usr/bin/env python3
"""
Download official PUBLIC (non-gated) `pnnbao97/VieNeu-TTS` models into `app/src/main/assets/models/`:
1. GGUF backbone (`pnnbao-ump/VieNeu-TTS-0.3B-q4-gguf`, fallback `pnnbao-ump/VieNeu-TTS-q4-gguf`) + `voices.json`
2. Public NeuCodec ONNX 24kHz FSQ Decoder (accepts 16-bit FSQ tokens `0..65535` generated by VieNeu-TTS GGUF):
   - Prioritizes verified public Apache-2.0 mirrors of `neuphonic/neucodec-onnx-decoder-int8`
     (`pnnbao-ump/neucodec-onnx-decoder-int8`, `TamPham92/neucodec-onnx-decoder-int8`,
     `aoiandroid/neuphonic-neucodec-onnx-decoder-int8-mirror`, `pnnbao-ump/neucodec-onnx-decoder`,
     plus dynamically discovered public non-gated HF mirrors).
   - Actively verifies each downloaded decoder via `onnxruntime` dry-run with FSQ tokens `[6181, 6377, 55510, 53535]`
     so incompatible VieNeu-TTS v2 decoders (e.g., `pnnbao-ump/VieNeu-Codec` requiring `content_ids` + `voice_embedding`)
     are never paired with the NeuCodec FSQ GGUF backbone.
3. Public NeuCodec ONNX 16kHz FSQ Encoder (`pnnbao-ump/neucodec-onnx-encoder`, `pnnbao-ump/distill-neucodec-onnx`,
   `KevinAHM/distill-neucodec-onnx`, or dynamically discovered public non-gated HF repos) — verified via
   `onnxruntime` 16kHz dry-run returning discrete FSQ tokens in `0..65535`.

Never relies on gated `neuphonic/*` repos that require Hugging Face login.

Usage:
  python3 scripts/download_vieneu_models.py <models_dir>
"""

import json
import os
import shutil
import sys
from typing import Dict, List, Optional, Tuple

import numpy as np
import onnxruntime as ort
from huggingface_hub import HfApi, hf_hub_download


def assert_not_lfs_pointer(path: str) -> None:
    sz = os.path.getsize(path)
    if sz < 256:
        with open(path, "rb") as f:
            head = f.read(256)
        if b"version https://git-lfs.github.com/spec/v1" in head:
            raise RuntimeError(f"File {path} is a Git LFS pointer ({sz} bytes), not binary data!")


def inspect_public_repo_files(api: HfApi, repo_id: str) -> Optional[List[str]]:
    """
    Check Hugging Face API for `repo_id`.
    Immediately skips private or gated repos (`gated != False`) so CI never fails with 401 GatedRepoError.
    Returns the exact list of file paths inside the repo if publicly accessible.
    """
    try:
        info = api.model_info(repo_id)
    except Exception as exc:
        print(f"  [skip] Cannot inspect {repo_id}: {exc}", flush=True)
        return None

    if getattr(info, "private", False):
        print(f"  [skip] Repo {repo_id} is private", flush=True)
        return None
    if getattr(info, "gated", False):
        print(f"  [skip] Repo {repo_id} is gated (requires HF login)", flush=True)
        return None

    siblings = getattr(info, "siblings", None) or []
    files = [s.rfilename for s in siblings if getattr(s, "rfilename", None)]
    if not files:
        try:
            files = api.list_repo_files(repo_id)
        except Exception as exc:
            print(f"  [skip] Cannot list files in {repo_id}: {exc}", flush=True)
            return None

    print(f"  [public] {repo_id}: {len(files)} files -> {files}", flush=True)
    return files


def download_file_safe(repo_id: str, filename: str, dest_path: str) -> bool:
    try:
        cached = hf_hub_download(repo_id=repo_id, filename=filename)
        assert_not_lfs_pointer(cached)
        os.makedirs(os.path.dirname(os.path.abspath(dest_path)), exist_ok=True)
        shutil.copy2(cached, dest_path)
        size_mb = os.path.getsize(dest_path) / (1024.0 * 1024.0)
        print(f"    -> saved {os.path.basename(dest_path)} ({size_mb:.2f} MB) from {repo_id}/{filename}", flush=True)
        return True
    except Exception as exc:
        print(f"  [warn] Download failed for {repo_id}/{filename}: {exc}", flush=True)
        if os.path.exists(dest_path):
            try:
                os.remove(dest_path)
            except OSError:
                pass
        return False


def find_external_data_files(chosen_onnx: str, all_files: List[str]) -> List[str]:
    """
    Find companion ONNX external data files (`.data`, `.onnx_data`, `.onnx.data`)
    living alongside `chosen_onnx` in the repository.
    """
    chosen_dir = os.path.dirname(chosen_onnx)
    chosen_base = os.path.basename(chosen_onnx)
    chosen_stem = os.path.splitext(chosen_base)[0]
    same_dir_onnx = [
        f for f in all_files
        if os.path.dirname(f) == chosen_dir and f.lower().endswith(".onnx")
    ]

    companions: List[str] = []
    for f in all_files:
        if os.path.dirname(f) != chosen_dir:
            continue
        bn = os.path.basename(f)
        low = bn.lower()
        is_ext_data = (
            low.endswith(".onnx.data")
            or low.endswith(".onnx_data")
            or low.endswith(".data")
        )
        if not is_ext_data:
            continue
        if bn.startswith(chosen_base) or bn.startswith(chosen_stem) or len(same_dir_onnx) == 1:
            companions.append(f)
    return companions


def cleanup_paths(paths: List[str]) -> None:
    for p in paths:
        if os.path.exists(p):
            try:
                os.remove(p)
            except OSError:
                pass


def download_onnx_with_companions(
    repo_id: str,
    chosen_onnx: str,
    all_files: List[str],
    dest_onnx_path: str,
    models_dir: str,
) -> Optional[List[str]]:
    """
    Download an ONNX graph plus any companion external `.data` / `.onnx_data` weight files.
    Returns list of all downloaded local file paths on success, or None on failure.
    """
    if not download_file_safe(repo_id, chosen_onnx, dest_onnx_path):
        return None

    downloaded: List[str] = [dest_onnx_path]
    companions = find_external_data_files(chosen_onnx, all_files)
    for extra in companions:
        extra_dest = os.path.join(models_dir, os.path.basename(extra))
        if not download_file_safe(repo_id, extra, extra_dest):
            cleanup_paths(downloaded)
            return None
        downloaded.append(extra_dest)
    return downloaded


def describe_io(nodes) -> List[Dict[str, object]]:
    return [{"name": n.name, "type": n.type, "shape": list(n.shape)} for n in nodes]


def verify_neucodec_decoder_onnx(onnx_path: str) -> Optional[Dict[str, object]]:
    """
    Verify via ONNX Runtime that `onnx_path` is a genuine NeuCodec 24kHz FSQ decoder
    compatible with `pnnbao-ump/VieNeu-TTS-0.3B-q4-gguf` speech tokens (`0..65535`):
      - Loads cleanly (including any external `.data` weights).
      - Expects a single integer token input (e.g., `codes`), NOT a VieNeu-Codec v2
        multi-input (`content_ids` + `voice_embedding`) graph whose codebook does not match FSQ 65536.
      - Successfully decodes 4 FSQ test tokens `[6181, 6377, 55510, 53535]` into >= 1000 finite float samples.
    """
    try:
        sess = ort.InferenceSession(onnx_path, providers=["CPUExecutionProvider"])
        inputs = sess.get_inputs()
        outputs = sess.get_outputs()
        in_desc = describe_io(inputs)
        out_desc = describe_io(outputs)
        print(f"    [verify decoder] inputs={in_desc} | outputs={out_desc}", flush=True)

        if len(inputs) != 1:
            print(
                f"    [reject decoder] Expected 1 FSQ token input (e.g. 'codes'), "
                f"but found {len(inputs)} inputs ({[i.name for i in inputs]}). "
                f"Incompatible with NeuCodec FSQ GGUF backbone!",
                flush=True,
            )
            return None

        inp = inputs[0]
        if "int" not in inp.type.lower():
            print(f"    [reject decoder] Expected integer input tensor, got {inp.type}", flush=True)
            return None

        dtype = np.int64 if "int64" in inp.type.lower() else np.int32
        test_codes = np.asarray([6181, 6377, 55510, 53535], dtype=dtype)
        rank = len(inp.shape)
        if rank == 3:
            tensor = test_codes.reshape(1, 1, -1)
        elif rank == 2:
            tensor = test_codes.reshape(1, -1)
        elif rank == 1:
            tensor = test_codes.reshape(-1)
        else:
            tensor = test_codes.reshape(1, 1, -1)

        out = sess.run(None, {inp.name: tensor})
        wav = np.asarray(out[0], dtype=np.float32).reshape(-1)
        if wav.size < 1000 or not np.all(np.isfinite(wav)):
            print(
                f"    [reject decoder] Dry-run output invalid (samples={wav.size}, finite={bool(np.all(np.isfinite(wav)))})",
                flush=True,
            )
            return None

        print(
            f"    [ok decoder] Verified NeuCodec FSQ 24kHz decoder: "
            f"4 tokens -> {wav.size} samples (peak={float(np.max(np.abs(wav))):.4f})",
            flush=True,
        )
        return {"inputs": in_desc, "outputs": out_desc}
    except Exception as exc:
        print(f"    [reject decoder] ONNX Runtime verification failed: {exc}", flush=True)
        return None


def verify_neucodec_encoder_onnx(onnx_path: str) -> Optional[Dict[str, object]]:
    """
    Verify via ONNX Runtime that `onnx_path` is a genuine NeuCodec 16kHz FSQ encoder:
      - Loads cleanly (including external `.data` weights).
      - Accepts 1.0s of 16kHz float32 audio (padded to multiple of 320) and emits discrete FSQ codes in `0..65535`.
    """
    try:
        sess = ort.InferenceSession(onnx_path, providers=["CPUExecutionProvider"])
        inputs = sess.get_inputs()
        outputs = sess.get_outputs()
        in_desc = describe_io(inputs)
        out_desc = describe_io(outputs)
        print(f"    [verify encoder] inputs={in_desc} | outputs={out_desc}", flush=True)

        if not inputs:
            return None

        t = np.linspace(0.0, 1.0, 16000, endpoint=False, dtype=np.float32)
        wav = (0.3 * np.sin(2.0 * np.pi * 220.0 * t)).astype(np.float32)
        feed: Dict[str, np.ndarray] = {}
        for inp in inputs:
            low = inp.name.lower()
            if "int" in inp.type.lower() or "len" in low:
                dt = np.int64 if "int64" in inp.type.lower() else np.int32
                feed[inp.name] = np.asarray([wav.size], dtype=dt)
            else:
                rank = len(inp.shape)
                if rank == 3:
                    feed[inp.name] = wav.reshape(1, 1, -1)
                elif rank == 2:
                    feed[inp.name] = wav.reshape(1, -1)
                else:
                    feed[inp.name] = wav.reshape(1, 1, -1)

        out = sess.run(None, feed)
        raw = np.asarray(out[0]).reshape(-1)
        valid_codes = [int(c) for c in raw.tolist() if 0 <= int(c) <= 65535]
        if len(valid_codes) < 15:
            print(
                f"    [reject encoder] Expected >= 15 FSQ codes for 1s audio, got {len(valid_codes)} "
                f"(dtype={raw.dtype}, shape={np.asarray(out[0]).shape})",
                flush=True,
            )
            return None

        print(
            f"    [ok encoder] Verified NeuCodec FSQ 16kHz encoder: "
            f"16000 samples -> {len(valid_codes)} codes (sample={valid_codes[:6]})",
            flush=True,
        )
        return {"inputs": in_desc, "outputs": out_desc}
    except Exception as exc:
        print(f"    [reject encoder] ONNX Runtime verification failed: {exc}", flush=True)
        return None


def discover_public_repos(api: HfApi, author: Optional[str] = None, search: Optional[str] = None, limit: int = 30) -> List[str]:
    found: List[str] = []
    try:
        models = api.list_models(author=author, search=search, limit=limit)
        for m in models:
            if getattr(m, "gated", False) or getattr(m, "private", False):
                continue
            repo_id = getattr(m, "id", None)
            if repo_id and repo_id not in found:
                found.append(repo_id)
    except Exception as exc:
        print(f"  [warn] HF discovery failed (author={author}, search={search}): {exc}", flush=True)
    return found


def pick_best_decoder_onnx(files: List[str]) -> Optional[str]:
    onnx_files = [f for f in files if f.lower().endswith(".onnx")]
    if not onnx_files:
        return None
    candidates = [f for f in onnx_files if "enc" not in os.path.basename(f).lower()]
    if not candidates:
        return None

    def score(path: str) -> Tuple[int, int, int, str]:
        bn = os.path.basename(path).lower()
        has_dec = 0 if ("dec" in bn or bn == "model.onnx") else 1
        has_int8 = 0 if ("int8" in bn or "q8" in bn or "quant" in bn) else 1
        return (has_dec, has_int8, len(path), path)

    candidates.sort(key=score)
    return candidates[0]


def pick_best_encoder_onnx(files: List[str], require_enc_keyword: bool) -> Optional[str]:
    onnx_files = [f for f in files if f.lower().endswith(".onnx")]
    if not onnx_files:
        return None
    enc_files = [
        f for f in onnx_files
        if "enc" in os.path.basename(f).lower() and "dec" not in os.path.basename(f).lower()
    ]
    if enc_files:
        enc_files.sort(
            key=lambda s: (
                0 if ("int8" in s.lower() or "quant" in s.lower() or "q8" in s.lower()) else 1,
                len(s),
                s,
            )
        )
        return enc_files[0]
    if require_enc_keyword:
        return None
    non_dec = [f for f in onnx_files if "dec" not in os.path.basename(f).lower()]
    return non_dec[0] if non_dec else None


def main() -> int:
    models_dir = sys.argv[1] if len(sys.argv) >= 2 else "app/src/main/assets/models"
    if os.path.exists(models_dir):
        shutil.rmtree(models_dir)
    os.makedirs(models_dir, exist_ok=True)

    api = HfApi()
    pnnbao_public_repos = discover_public_repos(api, author="pnnbao-ump", limit=50)
    print(f"Public repos discovered under pnnbao-ump ({len(pnnbao_public_repos)}): {pnnbao_public_repos}", flush=True)

    # =========================================================================
    # 1. Official VieNeu-TTS GGUF Backbone + voices.json (Public `pnnbao-ump`)
    # =========================================================================
    gguf_candidates: List[str] = [
        "pnnbao-ump/VieNeu-TTS-0.3B-q4-gguf",
        "pnnbao-ump/VieNeu-TTS-q4-gguf",
        "pnnbao-ump/VieNeu-TTS-0.3B-q8-gguf",
    ]
    for r in pnnbao_public_repos:
        if "gguf" in r.lower() and r not in gguf_candidates:
            gguf_candidates.append(r)

    gguf_repo_used: Optional[str] = None
    gguf_dest: Optional[str] = None
    voices_dest: Optional[str] = None

    print("\n=== [1/3] Downloading GGUF Backbone + voices.json ===", flush=True)
    for repo in gguf_candidates:
        files = inspect_public_repo_files(api, repo)
        if not files:
            continue
        gguf_files = [f for f in files if f.lower().endswith(".gguf")]
        if not gguf_files:
            continue
        gguf_files.sort(key=lambda s: (0 if "q4" in s.lower() else 1, len(s), s))
        chosen_gguf = gguf_files[0]
        dest = os.path.join(models_dir, os.path.basename(chosen_gguf))
        if not download_file_safe(repo, chosen_gguf, dest):
            continue
        gguf_dest = dest
        gguf_repo_used = repo

        voices_files = [f for f in files if os.path.basename(f).lower() == "voices.json"]
        if voices_files:
            v_dest = os.path.join(models_dir, "voices.json")
            if download_file_safe(repo, voices_files[0], v_dest):
                voices_dest = v_dest
        break

    if not gguf_dest:
        raise RuntimeError("Failed to download *.gguf from public pnnbao-ump repositories!")

    if not voices_dest:
        voice_fallback_repos = [
            "pnnbao-ump/VieNeu-TTS-0.3B",
            "pnnbao-ump/VieNeu-TTS",
            "pnnbao-ump/VieNeu-TTS-0.3B-q4-gguf",
        ]
        for v_repo in voice_fallback_repos:
            files = inspect_public_repo_files(api, v_repo) or []
            v_files = [f for f in files if os.path.basename(f).lower() == "voices.json"]
            if v_files:
                v_dest = os.path.join(models_dir, "voices.json")
                if download_file_safe(v_repo, v_files[0], v_dest):
                    voices_dest = v_dest
                    break

    # =========================================================================
    # 2. Public NeuCodec ONNX 24kHz FSQ Decoder (NO gated neuphonic repos!)
    #    Check public `pnnbao-ump` repos first, then verified public Apache-2.0
    #    mirrors of `neuphonic/neucodec-onnx-decoder-int8`.
    #    Every candidate is verified via `onnxruntime` dry-run with FSQ tokens
    #    [6181, 6377, 55510, 53535] so incompatible v2 codecs are skipped.
    # =========================================================================
    decoder_candidates: List[str] = [
        "pnnbao-ump/neucodec-onnx-decoder-int8",
        "pnnbao-ump/neucodec-onnx-decoder",
    ]
    for r in pnnbao_public_repos:
        low = r.lower()
        if ("neucodec" in low or "decoder" in low) and "enc" not in low and "vieneu-codec" not in low:
            if r not in decoder_candidates:
                decoder_candidates.append(r)

    for mirror in (
        "TamPham92/neucodec-onnx-decoder-int8",
        "aoiandroid/neuphonic-neucodec-onnx-decoder-int8-mirror",
    ):
        if mirror not in decoder_candidates:
            decoder_candidates.append(mirror)

    for query in ("neucodec-onnx-decoder-int8", "neucodec-onnx-decoder", "neucodec"):
        for r in discover_public_repos(api, search=query, limit=25):
            low = r.lower()
            if low.startswith("neuphonic/") or "vieneu-codec" in low:
                continue
            if r not in decoder_candidates:
                decoder_candidates.append(r)

    decoder_repo_used: Optional[str] = None
    decoder_file_used: Optional[str] = None
    decoder_schema: Optional[Dict[str, object]] = None
    print("\n=== [2/3] Downloading & Verifying Public NeuCodec ONNX Decoder (24kHz FSQ) ===", flush=True)
    for repo in decoder_candidates:
        files = inspect_public_repo_files(api, repo)
        if not files:
            continue
        chosen_dec = pick_best_decoder_onnx(files)
        if not chosen_dec:
            continue
        dec_dest = os.path.join(models_dir, "neucodec_decoder.onnx")
        downloaded = download_onnx_with_companions(repo, chosen_dec, files, dec_dest, models_dir)
        if not downloaded:
            continue
        schema = verify_neucodec_decoder_onnx(dec_dest)
        if schema is None:
            cleanup_paths(downloaded)
            continue
        decoder_repo_used = repo
        decoder_file_used = chosen_dec
        decoder_schema = schema
        break

    if not decoder_repo_used:
        raise RuntimeError(
            "Failed to download a verified NeuCodec FSQ 24kHz neucodec_decoder.onnx! Checked candidates: "
            + ", ".join(decoder_candidates)
        )

    # =========================================================================
    # 3. OPTIONAL NeuCodec ONNX 16kHz FSQ Encoder
    #    `pnnbao-ump` stores Vietnamese reference voices directly inside `voices.json`
    #    and does NOT require a standalone `neucodec_encoder.onnx`.
    #    If a verified public encoder exists we include it; otherwise we NEVER fail!
    # =========================================================================
    encoder_candidates: List[Tuple[str, bool]] = [
        ("pnnbao-ump/neucodec-onnx-encoder", False),
        ("pnnbao-ump/distill-neucodec-onnx", False),
        ("pnnbao-ump/VieNeu-TTS-0.3B-q4-gguf", True),
        ("KevinAHM/distill-neucodec-onnx", False),
    ]
    seen_enc = {r for r, _ in encoder_candidates}
    for r in pnnbao_public_repos:
        low = r.lower()
        if ("neucodec" in low or "encoder" in low) and "vieneu-codec" not in low and r not in seen_enc:
            encoder_candidates.append((r, "encoder" not in low))
            seen_enc.add(r)

    encoder_repo_used: Optional[str] = None
    encoder_file_used: Optional[str] = None
    encoder_schema: Optional[Dict[str, object]] = None
    print("\n=== [3/3] Checking OPTIONAL Public NeuCodec ONNX Encoder (non-fatal if absent) ===", flush=True)
    for repo, req_kw in encoder_candidates:
        files = inspect_public_repo_files(api, repo)
        if not files:
            continue
        chosen_enc = pick_best_encoder_onnx(files, require_enc_keyword=req_kw)
        if not chosen_enc:
            continue
        enc_dest = os.path.join(models_dir, "neucodec_encoder.onnx")
        downloaded = download_onnx_with_companions(repo, chosen_enc, files, enc_dest, models_dir)
        if not downloaded:
            continue
        schema = verify_neucodec_encoder_onnx(enc_dest)
        if schema is None:
            cleanup_paths(downloaded)
            continue
        encoder_repo_used = repo
        encoder_file_used = chosen_enc
        encoder_schema = schema
        break

    if not encoder_repo_used:
        print(
            "  [info] Optional neucodec_encoder.onnx was not found in public repos — "
            "continuing cleanly using GGUF + NeuCodec 24kHz Decoder + voices.json presets.",
            flush=True,
        )

    # =========================================================================
    # 4. Write manifest.json & summary
    # =========================================================================
    manifest = {
        "version": "vieneu-gguf-neucodec-2.3",
        "architecture": "pnnbao97/VieNeu-TTS",
        "sampleRate": 24000,
        "encoderSampleRate": 16000,
        "hasEncoder": bool(encoder_repo_used),
        "sources": {
            "gguf": gguf_repo_used,
            "decoder": f"{decoder_repo_used}/{decoder_file_used}",
            "encoder": f"{encoder_repo_used}/{encoder_file_used}" if encoder_repo_used else None,
        },
        "schemas": {
            "decoder": decoder_schema,
            "encoder": encoder_schema,
        },
        "files": sorted(set(os.listdir(models_dir) + ["vi_espeak_ipa.tsv", "manifest.json"])),
    }
    with open(os.path.join(models_dir, "manifest.json"), "w", encoding="utf-8") as mf:
        json.dump(manifest, mf, indent=2, ensure_ascii=False)

    print("\n=== FINAL DOWNLOADED MODEL BUNDLE ===", flush=True)
    total_bytes = 0
    for fn in sorted(os.listdir(models_dir)):
        fp = os.path.join(models_dir, fn)
        if os.path.isfile(fp):
            sz = os.path.getsize(fp)
            total_bytes += sz
            print(f"  - {fn} ({sz / (1024 * 1024):.2f} MB)", flush=True)
    print(f"TOTAL MODEL SIZE: {total_bytes / (1024 * 1024):.2f} MB", flush=True)

    if total_bytes < 50 * 1024 * 1024:
        raise RuntimeError(f"Downloaded bundle too small ({total_bytes} bytes)!")
    return 0


if __name__ == "__main__":
    sys.exit(main())
